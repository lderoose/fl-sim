def test_calculation(
    n_epochs,
    n_steps,
    n_workers,
    model,
    precision,
    cpr_class,
    k,
    k_as_factor,
    vrt_class,
    expected_result,
) -> None:
    cpr = {
        "name": cpr_class,
        "args": [],
        "kwargs": {"k": k, "k_as_factor": k_as_factor},
    }
    vrt = {
        "name": vrt_class,  # variant.ProjFL | variant.ErrorFeedback | None
        "args": [],
        "kwargs": {
            "alpha": 0.1,  # only for variant.ErrorFeedback
            "K": 1,
            "EF": True,  # only for variant.ProjFL
        },
    }

    cc = CommunicationCostComputer()(
        n_epochs=n_epochs,
        n_steps=n_steps,
        n_workers=n_workers,
        model=model(),
        precision=precision,
        cpr=cpr,
        vrt=vrt,
    )
    assert (
        cc == expected_result
    ), f"expected a cc of {expected_result}, get {cc} instead."
